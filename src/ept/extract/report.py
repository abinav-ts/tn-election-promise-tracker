from __future__ import annotations

import csv
import json
import statistics
from collections import Counter
from typing import Any, Optional

from ept import db
from ept.config import Config, get_config
from ept.extract.pages import calibration_path, read_records, term_dir
from ept.extract.units import read_units

LLM_PROMPTS = ("extract_promises", "dedup_check", "transcribe_page", "smoke_test")


def _csv(path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def _json(path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def _stats(values: list[float]) -> dict[str, Any]:
    v = [x for x in values if x is not None]
    return {"n": len(v), "min": min(v), "median": round(statistics.median(v), 4)} if v else {"n": 0}


def term_section(cfg: Config, conn, term: str) -> dict[str, Any]:
    ex = cfg.settings.extract
    records = read_records(cfg, term)
    promises = [dict(r) for r in db.query(conn, "SELECT * FROM promises WHERE term_id = ? ORDER BY promise_id",
                                          (term,))]
    dropped = [r for r in _csv(cfg.path("extract_dropped")) if r["term"] == term]
    failures = [r for r in _csv(cfg.path("extract_failures")) if r["term"] == term]
    dedup = [r for r in _csv(cfg.path("promise_dedup")) if r["term"] == term]
    below = [{"page": r["page"], "tamil_share": r["tamil_share"],
              "reason": "English words printed in a Latin font (D-046)" if r["route"] == "font_map"
              else f"English words on the page (D-051): {', '.join(r.get('latin_words', [])[:8])}"}
             for r in records if r.get("tamil_share") is not None and r["tamil_share"] < ex.fontmap_min_tamil_share
             and r["route"] != "ocr"]
    vision = [r for r in records if r["route"] == "vision"]
    return {
        "pages": len(records), "pages_by_route": dict(Counter(r["route"] for r in records)),
        "pages_awaiting_vision": [r["page"] for r in records if r.get("to_vision") and r["route"] != "vision"],
        "units": _json(term_dir(cfg, term) / "units_summary.json"),
        "promises_step": _json(term_dir(cfg, term) / "promises_summary.json"),
        "promises": len(promises), "dropped_by_kind": dict(Counter(r["kind"] for r in dropped)),
        "dedup_pairs": len(dedup), "dedup_drops": sum(1 for r in dedup if r["action"] == "dropped_later"),
        "failures": {"unresolved": sum(1 for r in failures if not r["resolved_by"]),
                     "resolved": dict(Counter(r["resolved_by"] for r in failures if r["resolved_by"])),
                     "by_rule": dict(Counter(r["rule"] for r in failures))},
        "quality": {"tamil_share": _stats([r.get("tamil_share") for r in records]),
                    "validity": _stats([r.get("validity") for r in records]),
                    "ocr_conf": _stats([r.get("ocr_conf") for r in records]),
                    "vision_pages": len(vision), "vision_cer": _stats([r.get("vision_cer") for r in vision]),
                    "vision_disagree": [r["page"] for r in vision
                                        if (r.get("vision_cer") or 0) > ex.vision_disagree_cer],
                    "accepted_below_threshold": below},
        "coverage": {k: v for k, v in _json(term_dir(cfg, term) / "coverage.json").items() if k != "items"},
        "coverage_status": dict(Counter(i["status"].split(":")[0] for i in
                                        _json(term_dir(cfg, term) / "coverage.json").get("items", []))),
        "per_section": Counter(p["section"] or "(none)" for p in promises).most_common(),
        "longest": [(p["promise_id"], len(p["text"].split()), p["text"]) for p in
                    sorted(promises, key=lambda p: -len(p["text"].split()))[:10]],
        "shortest": [(p["promise_id"], len(p["text"].split()), p["text"]) for p in
                     sorted(promises, key=lambda p: len(p["text"].split()))[:10]],
    }


def llm_usage(cfg: Config) -> dict[str, Any]:
    path = cfg.path("llm_usage_log")
    out: dict[str, dict[str, int]] = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            r = json.loads(line)
            if r["prompt"] in LLM_PROMPTS and r["backend"] == "bulk":
                d = out.setdefault(f"{r['prompt']} / {r['model']}", {"calls": 0, "cache_hits": 0, "failed": 0})
                d["cache_hits" if r["cache_hit"] else "calls"] += 1
                d["failed"] += not r["ok"]
    return out


def render(data: dict[str, Any]) -> str:
    L = ["# Stage 02 — promise extraction report", "", f"Generated by `ept extract report`. Terms: "
         + ", ".join(data["terms"]) + ". " + data["note"], ""]
    L += ["## 1. Per term", "", "| Term | Pages (route) | Units (marker) | Promises | Dropped (kind) | Dedup drops "
          "| Failures unresolved / resolved |", "|---|---|---|---|---|---|---|"]
    for t, s in data["per_term"].items():
        L.append(f"| {t} | {s['pages']} {s['pages_by_route']} | {s['units'].get('units', 0)} "
                 f"{s['units'].get('by_marker', {})} | {s['promises']} | {s['dropped_by_kind']} | {s['dedup_drops']} "
                 f"/ {s['dedup_pairs']} pairs | {s['failures']['unresolved']} / {s['failures']['resolved']} |")
    L += ["", "Character accounting (units + furniture = page text): " + "; ".join(
        f"{t} {'complete' if s['units'].get('accounted') else 'INCOMPLETE'} ({s['units'].get('unit_chars')} + "
        f"{s['units'].get('furniture_chars')} of {s['units'].get('page_chars')})" for t, s in data["per_term"].items()
        if s["units"]), ""]
    L += ["## 2. Text quality", "", f"OCR calibration (Tesseract `tam` at {data['calibration'].get('ppi')} ppi on "
          f"{data['calibration'].get('reference_term')} pages {[p['page'] for p in data['calibration'].get('pages', [])]}): "
          f"CER **{data['calibration'].get('cer')}** (optimistic: black-on-white reference). Gate `max_cer` "
          f"{data['gate_max_cer']} (D-048).", "",
          "| Term | Tamil share (min / median) | Validity (min / median) | OCR conf (min / median) | Vision pages "
          "| Vision-vs-OCR CER (min / median) | > disagree threshold | Awaiting vision |", "|---|---|---|---|---|---|---|---|"]
    for t, s in data["per_term"].items():
        q = s["quality"]
        f = lambda d: f"{d.get('min', '–')} / {d.get('median', '–')}"  # noqa: E731
        L.append(f"| {t} | {f(q['tamil_share'])} | {f(q['validity'])} | {f(q['ocr_conf'])} | {q['vision_pages']} | "
                 f"{f(q['vision_cer'])} | {q['vision_disagree']} | {len(s['pages_awaiting_vision'])} |")
    below = [(t, b) for t, s in data["per_term"].items() for b in s["quality"]["accepted_below_threshold"]]
    if below:
        L += ["", "Pages accepted below the Tamil-share threshold (acceptance criterion 2):", ""]
        L += [f"- {t} p{b['page']}: share {b['tamil_share']} — {b['reason']}" for t, b in below]
    L += ["", "## 3. Coverage (running-number manifestos)", ""]
    for t, s in data["per_term"].items():
        if s["coverage"]:
            c = s["coverage"]
            L.append(f"- {t}: {c['main_items']} main items; status {s['coverage_status']}; not printed "
                     f"(explained) {c['not_printed']}; **unexplained {c['unexplained']}**")
    L += ["", "## 4. Promises per section (top 25 per term; full list in the JSON)", ""]
    for t, s in data["per_term"].items():
        L.append(f"**{t}** ({len(s['per_section'])} sections): " + "; ".join(f"{k} {v}" for k, v in s["per_section"][:25]))
        L.append("")
    L += ["## 5. Longest and shortest promises", ""]
    for t, s in data["per_term"].items():
        L.append(f"**{t}** longest: " + " | ".join(f"{i} ({n} w): {x}" for i, n, x in s["longest"]))
        L.append("")
        L.append(f"**{t}** shortest: " + " | ".join(f"{i} ({n} w): {x}" for i, n, x in s["shortest"]))
        L.append("")
    L += ["## 6. LLM calls (bulk backend)", "", "| Prompt / model | Calls | Cache hits | Failed |", "|---|---|---|---|"]
    L += [f"| {k} | {v['calls']} | {v['cache_hits']} | {v['failed']} |" for k, v in data["llm"].items()]
    L += ["", "## 7. Known limitations", ""] + [f"- {x}" for x in data["limitations"]]
    return "\n".join(L) + "\n"


LIMITATIONS = [
    "DMK bold headings mix topic headings and single-item titles; an item without its own title inherits the "
    "previous bold heading as `section` (typography can't tell them apart).",
    "TVK-2026 is deferred (D-053): its transcription runs daily within the free quota; units, extraction and "
    "freeze follow before stage 07.",
    "Tamil-source V3 checks are flags, not failures: transliterated names can't be matched mechanically.",
]


def run_report(term: Optional[str] = None) -> dict[str, Any]:
    cfg = get_config()
    terms = [term] if term else [t for t in cfg.profiles() if read_records(cfg, t)]
    conn = db.connect()
    db.init_schema(conn)
    data = {"terms": terms, "per_term": {t: term_section(cfg, conn, t) for t in terms},
            "calibration": _json(calibration_path(cfg)), "gate_max_cer": cfg.settings.extract.ocr_gate.max_cer,
            "llm": llm_usage(cfg), "limitations": LIMITATIONS,
            "note": "Frozen terms: " + (", ".join(cfg.settings.extract.frozen_terms) or "none") + "."}
    conn.close()
    cfg.path("extraction_json").parent.mkdir(parents=True, exist_ok=True)
    cfg.path("extraction_json").write_text(json.dumps(data, ensure_ascii=False, indent=1, default=str),
                                           encoding="utf-8")
    cfg.path("extraction_md").write_text(render(data), encoding="utf-8")
    return {"terms": len(terms), "promises": sum(s["promises"] for s in data["per_term"].values()),
            "path": str(cfg.path("extraction_md"))}
